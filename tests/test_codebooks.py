# -*- coding: utf-8 -*-

"""Tests for the codebooks that ship inside the package.

An entropy codec *is* its frequency table, so without these an installed
package could encode nothing. They are regenerated by
``scripts/make_codebooks.py``; if this module fails, that is the thing to run.
"""

from __future__ import annotations

import subprocess
import sys

import pytest

from osmiumchem import api
from osmiumchem import codebook as cb
from osmiumchem.api import DEFAULT_CORPUS

CAFFEINE = "CN1C=NC2=C1C(=O)N(C)C(=O)N2C"
CAFFEINE_CANONICAL = "Cn1c(=O)c2c(ncn2C)n(C)c1=O"

SHIPPED = sorted(cb.bundled_root().glob(f"*{cb.SUFFIX}")) if cb.bundled_root().is_dir() else []

#: Families whose fitted state is counts and alphabets. The others decode by
#: looking a payload up in a library of molecules, so shipping one would ship
#: the corpus.
SHIPPABLE_FAMILIES = {"string", "entropy"}

pytestmark = pytest.mark.skipif(not SHIPPED, reason="no codebooks have been generated in this checkout")


def test_some_codebooks_ship():
    assert SHIPPED
    assert DEFAULT_CORPUS in api.list_codebooks()


@pytest.mark.parametrize("path", SHIPPED, ids=lambda path: path.name)
def test_every_shipped_codebook_loads_and_matches_its_name(path):
    # Loading is the staleness check: a container format this build cannot
    # read raises, and the message says to refit.
    book = cb.load(path)
    assert cb.bundled_path(book.provenance.codec, book.provenance.corpus) == path
    assert book.provenance.fitted > 0


@pytest.mark.parametrize("path", SHIPPED, ids=lambda path: path.name)
def test_no_shipped_codebook_carries_a_library_of_molecules(path):
    # The corpora must stay out of the package, and a lookup-decoded codec
    # keeps its library inside the codebook.
    book = cb.load(path)
    family = book.codec.describe()["family"]
    assert family in SHIPPABLE_FAMILIES
    assert book.provenance.library == 0


def test_every_corpus_ships_the_same_codecs():
    # A codec missing for one corpus means a half-finished generation run.
    by_corpus: dict[str, set[str]] = {}
    for path in SHIPPED:
        provenance = cb.load(path).provenance
        by_corpus.setdefault(provenance.corpus, set()).add(provenance.codec)
    sets = list(by_corpus.values())
    assert all(names == sets[0] for names in sets), {k: len(v) for k, v in by_corpus.items()}


def test_the_default_codec_round_trips_with_nothing_on_disk(tmp_path, monkeypatch):
    # The fresh-install path: no cache, no corpora, no home directory to read.
    monkeypatch.setenv("OSMIUMCHEM_CACHE", str(tmp_path / "cache"))
    # Both, because Path.home() reads HOME on POSIX and USERPROFILE on Windows.
    monkeypatch.setenv("HOME", str(tmp_path / "home"))
    monkeypatch.setenv("USERPROFILE", str(tmp_path / "home"))
    codec = api.load_codec("smiles+arith-o4")
    result = codec.round_trip(CAFFEINE)
    assert result.verdict == "ok"
    assert result.decoded.smiles == CAFFEINE_CANONICAL
    assert result.bits < 1000


def test_a_payload_crosses_between_processes():
    # Two processes holding the same shipped table is the whole point: encode
    # and decode are separate commands.
    encoded = api.load_codec("smiles+arith-o4").encode(CAFFEINE)
    decoded = subprocess.run(  # noqa: S603 - fixed argv, this interpreter
        [
            sys.executable,
            "-c",
            "import sys, osmiumchem as oc; print(oc.load_codec('smiles+arith-o4').decode(sys.argv[1]).smiles)",
            encoded.text,
        ],
        capture_output=True,
        text=True,
        check=True,
    )
    assert decoded.stdout.strip() == CAFFEINE_CANONICAL


def test_a_corpus_specific_codebook_differs_from_the_default():
    # Different chemistry, different table, so the bit cost should differ too.
    corpora = api.list_codebooks("smiles+arith-o4")
    others = [name for name in corpora if name != DEFAULT_CORPUS]
    if not others:
        pytest.skip("only one corpus has been generated")
    default = api.load_codec("smiles+arith-o4")
    other = api.load_codec("smiles+arith-o4", corpus=others[0])
    assert default.provenance.corpus != other.provenance.corpus
    assert other.round_trip(CAFFEINE).decoded.smiles == CAFFEINE_CANONICAL
